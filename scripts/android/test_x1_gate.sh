#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────
# pili-pos - self-test of scripts/android/x1_gate.sh
#
# Usage: bash scripts/android/test_x1_gate.sh
#
# Runs x1_gate.sh against throwaway git repositories (PILI_X1_ROOT, PILI_X1_FORK) with
# stub sub-gates (PILI_X1_P1B, PILI_X1_P4), a stub parity command (PILI_X1_PARITY), a
# stub check_repro.sh and a stub docker. Never touches the real repository, needs no
# Gradle, no network, no Docker, no emulator.
# Cases: option parsing and forwarding to the sub-gates, prefixing, the six waivers and
# the checks that are not waivable (also under the other prefix), a sub-gate without a
# total line, x1-paths, x1-scope (in scope, out of scope, not guarded, untracked),
# x1-lock-additive (added package, version bump, checksum change), x1-parity, the
# selftest line, x1-linux-repro, the header and the total line format.
# Prints one line per case and '<N> cases passed'; exits 1 when a case fails.
# ─────────────────────────────────────────────────────────────────
set -uo pipefail
export LC_ALL=C

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd -P)"
GATE="$ROOT/scripts/android/x1_gate.sh"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
export HOME="$TMP/home"
mkdir -p "$HOME"
export PILI_X1_NESTED=1
unset PILI_X1_P1B PILI_X1_P4 PILI_X1_ROOT PILI_X1_FORK PILI_X1_PARITY
pass=0
fail=0

ok() { pass=$((pass + 1)); printf 'TEST | %s | PASS\n' "$1"; }
bad() { fail=$((fail + 1)); printf 'TEST | %s | FAIL | %s\n' "$1" "$2"; }

# check NAME CONDITION-RESULT(0 = true) DETAIL
check() { if [[ "$2" -eq 0 ]]; then ok "$1"; else bad "$1" "$3"; fi; }

# t CONDITION...: exit status of a test expression, for check().
t() { if "$@"; then echo 0; else echo 1; fi; }

# A stub sub-gate. STUB_FAIL: space-separated check names that FAIL. STUB_NO_TOTAL=1:
# no total line. STUB_LOG records the arguments. One copy per sub-gate, same content.
STUB="$TMP/stub_subgate.sh"
cat >"$STUB" <<'STUB'
#!/usr/bin/env bash
printf '%s %s\n' "$STUB_NAME" "$*" >>"${STUB_LOG:-/dev/null}"
names="$STUB_CHECKS"
failed=0
for n in $names; do
    case " ${STUB_FAIL:-} " in
    *" $n "*)
        echo "GATE | $n | FAIL | $n broke"
        echo "stub stderr of $n" >&2
        failed=$((failed + 1))
        ;;
    *) echo "GATE | $n | PASS | $n ok" ;;
    esac
done
echo "GATE | skipped-one | SKIP | later"
[[ "${STUB_NO_TOTAL:-0}" == "1" ]] && exit "$failed"
if [[ "$failed" -eq 0 ]]; then
    echo "GATE | total | PASS | 0 failed ($((2 + $(echo $names | wc -w))) checks)"
    exit 0
fi
echo "GATE | total | FAIL | $failed failed (x checks)"
exit 1
STUB
P1B_CHECKS="linux-frozen hygiene-cargo-lock freeze-tag rust-fmt rust-clippy"
P4_CHECKS="linux-frozen freeze-tag hygiene-root-lock hygiene-paths rust-tests command-parity"
P1B_STUB="$TMP/p1b.sh"
P4_STUB="$TMP/p4.sh"
printf '#!/usr/bin/env bash\nSTUB_NAME=p1b\nSTUB_CHECKS="%s"\nsource "%s"\n' "$P1B_CHECKS" "$STUB" >"$P1B_STUB"
printf '#!/usr/bin/env bash\nSTUB_NAME=p4\nSTUB_CHECKS="%s"\nsource "%s"\n' "$P4_CHECKS" "$STUB" >"$P4_STUB"
# the stubs are 'source'd by bash, so they need no exec bit; BASH_SOURCE aside they behave as scripts

# tgit REPO git-args...: git inside a throwaway repository only.
tgit() {
    local r="$1"
    shift
    if [[ -z "$r" || "$r" != "$TMP"/* || ! -d "$r/.git" ]]; then
        echo "tgit: refusing to run git in '$r'" >&2
        exit 1
    fi
    git -C "$r" -c user.name=t -c user.email=t@t -c commit.gpgsign=false "$@"
}

LOCK_ROOT='# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "alpha"
version = "1.0.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "aaaa"

[[package]]
name = "beta"
version = "2.1.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "bbbb"
dependencies = [
 "alpha",
]

[[package]]
name = "pos-core"
version = "1.1.0"
dependencies = [
 "alpha",
]
'
LOCK_ANDROID='version = 4

[[package]]
name = "gamma"
version = "0.3.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "cccc"

[[package]]
name = "pos-ffi"
version = "1.1.0"
'

# new_repo: a throwaway repository with a fork commit (tagged base). Prints its path.
# FORK is set (in the caller's shell, not in the command substitution) by repo_fork.
new_repo() {
    local r
    r="$(mktemp -d "$TMP/repo.XXXXXX")"
    mkdir -p "$r/scripts/android" "$r/docs/android" "$r/crates/pos-db/src" "$r/crates/pos-export/src" \
        "$r/deploy" "$r/ui/src" "$r/android/rust"
    echo "x" >"$r/README.md"
    echo "pub fn schema() {}" >"$r/crates/pos-db/src/schema.rs"
    echo 'channel = "1.99.0"' >"$r/rust-toolchain.toml"
    echo "#!/bin/sh" >"$r/deploy/build-release.sh"
    echo "export const t = 1" >"$r/ui/src/i18n.ts"
    printf '%s' "$LOCK_ROOT" >"$r/Cargo.lock"
    printf '%s' "$LOCK_ANDROID" >"$r/android/rust/Cargo.lock"
    {
        git -C "$r" init -q -b main
        tgit "$r" add -A
        tgit "$r" commit -q -m "chore: fork"
        tgit "$r" tag base
    } >/dev/null 2>&1
    printf '%s' "$r"
}
fork_of() { tgit "$1" rev-parse base; }

# commit_all REPO: commit everything after the fork (the card's work).
commit_all() {
    tgit "$1" add -A >/dev/null 2>&1
    tgit "$1" commit -q -m "feat(gate): work" >/dev/null 2>&1
}

# run_gate REPO [VAR=value]... -- ARGS...: sets OUT, ERR, RC. The default parity is a pass.
run_gate() {
    local repo="$1" envs=()
    shift
    while [[ $# -gt 0 && "$1" != "--" ]]; do
        envs+=("$1")
        shift
    done
    shift
    [[ "$repo" == "$TMP"/* && -d "$repo/.git" ]] || { echo "run_gate: bad repo '$repo'" >&2; exit 1; }
    OUT="$(env PILI_X1_ROOT="$repo" PILI_X1_P1B="$P1B_STUB" PILI_X1_P4="$P4_STUB" PILI_X1_FORK="$(fork_of "$repo")" \
        PILI_X1_PARITY="true" STUB_LOG="$TMP/stub.log" ${envs[@]+"${envs[@]}"} \
        bash "$GATE" --fast --base base "$@" 2>"$TMP/err.txt")"
    RC=$?
    ERR="$(cat "$TMP/err.txt")"
}

status_of() { printf '%s\n' "$OUT" | sed -n "s/^GATE | $1 | \\([A-Z]*\\) | .*/\\1/p" | head -n 1; }
detail_of() { printf '%s\n' "$OUT" | sed -n "s/^GATE | $1 | [A-Z]* | //p" | head -n 1; }
total_of() { printf '%s\n' "$OUT" | sed -n 's/^GATE | total | \([A-Z]*\) | .*/\1/p'; }
total_line() { printf '%s\n' "$OUT" | grep '^GATE | total | ' | tail -n 1; }

# ── 1. all PASS ─────────────────────────────────────────────────
R="$(new_repo)"
run_gate "$R" --
check "all checks pass: total PASS, exit 0" "$([[ "$(total_of)" == PASS && $RC -eq 0 ]] && echo 0 || echo 1)" "rc=$RC total=$(total_line)"
check "sub-gate lines are prefixed root: and android:" \
    "$([[ "$(status_of root:rust-fmt)" == PASS && "$(status_of android:rust-tests)" == PASS && "$(status_of android:linux-frozen)" == PASS ]] && echo 0 || echo 1)" "$OUT"
check "a sub-gate total line is dropped" "$([[ "$(printf '%s\n' "$OUT" | grep -c '^GATE | total | ')" == 1 ]] && echo 0 || echo 1)" "$OUT"
check "SKIP lines of a sub-gate are kept" "$([[ "$(status_of root:skipped-one)" == SKIP ]] && echo 0 || echo 1)" "$OUT"
check "the own checks are printed (paths SKIP, scope, lock, parity)" \
    "$([[ "$(status_of x1-paths)" == SKIP && "$(status_of x1-scope)" == PASS && "$(status_of x1-lock-additive)" == PASS && "$(status_of x1-parity)" == PASS ]] && echo 0 || echo 1)" "$OUT"
# 5 + 6 sub-gate PASS lines + 2 SKIP lines + 4 own checks = 17 checks
check "total line format" "$([[ "$(total_line)" =~ ^GATE\ \|\ total\ \|\ PASS\ \|\ 0\ failed\ \([0-9]+\ checks,\ 0\ waived\)$ ]] && echo 0 || echo 1)" "$(total_line)"
check "the total counts the sub-gate checks" "$([[ "$(total_line)" == *"(17 checks, 0 waived)"* ]] && echo 0 || echo 1)" "$(total_line)"

# ── 2. the six waivers ──────────────────────────────────────────
for pair in "root:linux-frozen:linux-frozen" "root:hygiene-cargo-lock:hygiene-cargo-lock" \
    "android:linux-frozen:linux-frozen" "android:freeze-tag:freeze-tag" \
    "android:hygiene-root-lock:hygiene-root-lock" "android:hygiene-paths:hygiene-paths"; do
    full="${pair%:*}"
    raw="${pair##*:}"
    # linux-frozen and freeze-tag exist in both stubs, so both prefixes are failed at once
    run_gate "$R" "STUB_FAIL=$raw" --
    check "waiver: $full is WAIVED" "$([[ "$(status_of "$full")" == WAIVED ]] && echo 0 || echo 1)" "$OUT"
    check "waiver: $full detail carries the X1 note" \
        "$([[ "$(detail_of "$full")" == "$raw broke (X1 lane: Linux freeze reopened, X1D2)" ]] && echo 0 || echo 1)" "$(detail_of "$full")"
done
# one waived check, alone: total PASS and the waived count
run_gate "$R" "STUB_FAIL=hygiene-paths" --
check "one waived check: total PASS, exit 0, 1 waived" \
    "$([[ "$(total_of)" == PASS && $RC -eq 0 && "$(total_line)" == *"0 failed (17 checks, 1 waived)" ]] && echo 0 || echo 1)" "rc=$RC $(total_line)"
check "a waived check does not print to the failure count" "$([[ "$(status_of android:hygiene-paths)" == WAIVED ]] && echo 0 || echo 1)" "$OUT"
run_gate "$R" "STUB_FAIL=hygiene-cargo-lock" --
check "root:hygiene-cargo-lock alone is waived (the android stub has no such check)" \
    "$([[ "$(status_of root:hygiene-cargo-lock)" == WAIVED && "$(total_of)" == PASS ]] && echo 0 || echo 1)" "$OUT"
check "sub-gate stderr passes through" "$([[ "$ERR" == *"stub stderr of hygiene-cargo-lock"* ]] && echo 0 || echo 1)" "$ERR"

# ── 3. not waivable ─────────────────────────────────────────────
run_gate "$R" "STUB_FAIL=rust-tests" --
check "android:rust-tests FAIL: total FAIL, exit 1" \
    "$([[ "$(status_of android:rust-tests)" == FAIL && "$(total_of)" == FAIL && $RC -eq 1 && "$(total_line)" == *"1 failed (17 checks, 0 waived)" ]] && echo 0 || echo 1)" "rc=$RC $(total_line)"
run_gate "$R" "STUB_FAIL=freeze-tag" --
check "root:freeze-tag (other prefix) is not waived" \
    "$([[ "$(status_of root:freeze-tag)" == FAIL && "$(status_of android:freeze-tag)" == WAIVED && "$(total_of)" == FAIL ]] && echo 0 || echo 1)" "$OUT"
run_gate "$R" "STUB_FAIL=rust-fmt linux-frozen" --
check "a real failure next to a waived one still fails" \
    "$([[ "$(status_of root:rust-fmt)" == FAIL && "$(status_of root:linux-frozen)" == WAIVED && "$(total_line)" == *"1 failed"*"2 waived)" ]] && echo 0 || echo 1)" "$(total_line)"
run_gate "$R" "STUB_FAIL=rust-clippy" --
check "root:rust-clippy FAIL: total FAIL" "$([[ "$(status_of root:rust-clippy)" == FAIL && $RC -eq 1 ]] && echo 0 || echo 1)" "$OUT"
run_gate "$R" "STUB_NO_TOTAL=1" --
check "a sub-gate without a total line fails" \
    "$([[ "$(status_of root:total)" == FAIL && "$(status_of android:total)" == FAIL && $RC -eq 1 ]] && echo 0 || echo 1)" "$OUT"

# ── 4. argument forwarding ──────────────────────────────────────
run_gate_args() { # env-less call with chosen gate args; sets OUT RC; log in $TMP/stub.log
    : >"$TMP/stub.log"
    OUT="$(env PILI_X1_ROOT="$R" PILI_X1_P1B="$P1B_STUB" PILI_X1_P4="$P4_STUB" PILI_X1_FORK="$(fork_of "$R")" \
        PILI_X1_PARITY="true" STUB_LOG="$TMP/stub.log" bash "$GATE" "$@" 2>/dev/null)"
    RC=$?
}
log_of() { sed -n "s/^$1 //p" "$TMP/stub.log"; }
run_gate_args --fast --base base
check "--fast: p1b gets --base base --fast, p4 gets --base base --fast" \
    "$([[ "$(log_of p1b)" == "--base base --fast" && "$(log_of p4)" == "--base base --fast" ]] && echo 0 || echo 1)" "$(cat "$TMP/stub.log")"
run_gate_args --base base
check "full mode: p1b without --fast, p4 with --fast (no --app)" \
    "$([[ "$(log_of p1b)" == "--base base" && "$(log_of p4)" == "--base base --fast" ]] && echo 0 || echo 1)" "$(cat "$TMP/stub.log")"
check "full mode with PILI_X1_NESTED=1: x1-selftest is SKIP" "$([[ "$(status_of x1-selftest)" == SKIP ]] && echo 0 || echo 1)" "$OUT"
run_gate_args --base base --app --android --app-e2e --allow '^x$' --linux-repro
check "--app/--android/--app-e2e: p4 without --fast, with --android --app-e2e; no --app, --allow or --linux-repro forwarded" \
    "$([[ "$(log_of p4)" == "--base base --android --app-e2e" && "$(log_of p1b)" == "--base base" ]] && echo 0 || echo 1)" "$(cat "$TMP/stub.log")"
run_gate_args --base base --exit
check "--exit: both get --exit, p4 gets --android and no --fast" \
    "$([[ "$(log_of p1b)" == "--base base --exit" && "$(log_of p4)" == "--base base --android --exit" ]] && echo 0 || echo 1)" "$(cat "$TMP/stub.log")"
run_gate_args --fast --base base --exit --app
check "--fast --exit --app: p1b has --fast and --exit, p4 neither --fast nor duplicates" \
    "$([[ "$(log_of p1b)" == "--base base --fast --exit" && "$(log_of p4)" == "--base base --android --exit" ]] && echo 0 || echo 1)" "$(cat "$TMP/stub.log")"

# ── 5. usage ────────────────────────────────────────────────────
for bad_args in "--bogus" "--base" "--allow"; do
    # shellcheck disable=SC2086
    PILI_X1_ROOT="$R" bash "$GATE" $bad_args >/dev/null 2>&1
    check "usage error exits 2: $bad_args" "$([[ $? -eq 2 ]] && echo 0 || echo 1)" "rc=$?"
done
HELP="$(bash "$GATE" --help 2>&1)"
rc=$?
check "--help exits 0 and prints the header" "$([[ $rc -eq 0 && "$HELP" == *"X1 gate"* && "$HELP" == *"Usage:"* ]] && echo 0 || echo 1)" "rc=$rc"
miss=""
for w in root:linux-frozen root:hygiene-cargo-lock android:linux-frozen android:freeze-tag android:hygiene-root-lock android:hygiene-paths; do
    [[ "$HELP" == *"$w"* ]] || miss="$miss $w"
done
check "--help names the six waivable checks" "$([[ -z "$miss" ]] && echo 0 || echo 1)" "missing:$miss"
# every X1_SCOPE alternative of the script is listed in the header
miss=""
while IFS= read -r alt; do
    [[ -n "$alt" ]] || continue
    printf '%s\n' "$HELP" | grep -qF -- "$alt" || miss="$miss $alt"
done < <(sed -n "/^X1_SCOPE=(/,/^)/p" "$GATE" | sed -n "s/^    '\\(.*\\)'\$/\\1/p")
check "--help lists every X1_SCOPE alternative" "$([[ -z "$miss" ]] && echo 0 || echo 1)" "missing:$miss"
check "the array X1_WAIVABLE holds six names" \
    "$([[ "$(sed -n '/^X1_WAIVABLE=(/,/^)/p' "$GATE" | grep -c ':')" == 6 ]] && echo 0 || echo 1)" "array does not hold six names"

