tgit "$R" add -A >/dev/null 2>&1
run_gate "$R" --
check "x1-scope: a staged modification is caught" "$([[ "$(status_of x1-scope)" == FAIL ]] && echo 0 || echo 1)" "$(detail_of x1-scope)"
R="$(new_repo)"
echo "notes" >"$R/docs/android/notes.md"
commit_all "$R"
run_gate "$R" --
check "x1-scope: a non-guarded path (docs/android/notes.md) is ignored" \
    "$([[ "$(status_of x1-scope)" == PASS && "$(detail_of x1-scope)" == "0 guarded file(s)"* ]] && echo 0 || echo 1)" "$(detail_of x1-scope)"
